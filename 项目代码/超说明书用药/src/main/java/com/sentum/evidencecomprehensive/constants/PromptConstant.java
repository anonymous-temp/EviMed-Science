    public static String getPrompt(String str, Object... objects) {
        // 使用正则表达式匹配无效占位符（如 %v）
        Pattern pattern = Pattern.compile("%(?![a-zA-Z0-9_])");
        Matcher matcher = pattern.matcher(str);

        // 替换所有无效占位符
        str = matcher.replaceAll("%%");

        // 使用格式化工具格式化字符串
        if (objects.length > 0) {
            return String.format(str, objects);
        } else {
            return str.replace("%%", "%"); // 如果没有对象传入，将 %% 还原为 %
        }
    }
