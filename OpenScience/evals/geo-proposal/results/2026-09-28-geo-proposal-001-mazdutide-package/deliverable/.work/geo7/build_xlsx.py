def rate(m):
    if m is None or m.get("value") is None:
        return "未测"
    if m["value"] is None:
        return "未测"
    if m.get("num") is None:
        return f'{m["value"]}（衍生指数，没有分子分母）'
    pct = f'{m["value"]}%'
    if m["den"] < 30:
        return f'{pct}（{m["num"]}/{m["den"]}，样本不足，只作参考）'
    return f'{pct}（{m["num"]}/{m["den"]}）'


def cell(m, key="value"):
    if not m:
        return "未测"
    v = m.get(key)
    if v is None:
        return "未测"
    if m.get("den") is not None and m["den"] < 30:
        return f'{v}%（样本不足，{m["num"]}/{m["den"]}）'
    if m.get("num") is not None:
        return f'{v}%（{m["num"]}/{m["den"]}）'
    return str(v)


