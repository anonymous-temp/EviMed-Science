import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, expect, it, vi } from "vitest";
import { VcrLiteratureSource } from "./VcrLiteratureSource";
const mocks = vi.hoisted(() => ({ listSources: vi.fn(), addSourceLink: vi.fn(), productRequest: vi.fn(), pickFiles: vi.fn(), uploadFilesToWorkspace: vi.fn() }));
vi.mock("@/lib/sourceClient", () => mocks);
vi.mock("@/lib/productClient", () => mocks);
vi.mock("@/lib/backend", () => mocks);
const source = { id: "source-1", display: { title: "Outcome trial" } };
const preview = { sourceId: "source-1", generation: 3, textSha256: "preserved-hash", title: "Outcome trial", status: "complete", missing: [], parameters: [{ id: "p-1", value: 4, unit: "mg", quote: "Difference was 4 mg.", start: 0, end: 20 }], supportedProfiles: [{ method: "patients.continuous", label: "连续结局参考场景", fields: [{ key: "truth.effect", label: "结局差值", unit: "outcome units", required: true }] }] };
beforeEach(() => { vi.clearAllMocks(); mocks.listSources.mockResolvedValue({ items: [source] }); mocks.productRequest.mockResolvedValue(preview); });
it("preserves source identity and binds candidate IDs without submitting caller-supplied numeric values", async () => {
  const onChange = vi.fn();
  render(<VcrLiteratureSource studyId="study-1" projectId="project-1" onChange={onChange} />);
  await screen.findByRole("option", { name: "Outcome trial" });
  await userEvent.selectOptions(screen.getByLabelText("已有文献"), "source-1");
  await userEvent.click(screen.getByRole("button", { name: "读取文献参数" }));
  expect(await screen.findByText("Difference was 4 mg.")).toBeInTheDocument();
  await userEvent.selectOptions(screen.getByLabelText("参数化参考场景"), "patients.continuous");
  await userEvent.selectOptions(screen.getByLabelText("结局差值（outcome units）"), "p-1");
  await waitFor(() => expect(onChange).toHaveBeenLastCalledWith({ literatureSource: { sourceId: "source-1", generation: 3, textSha256: "preserved-hash" }, title: "Outcome trial", executionProfile: "patients.continuous", parameterBindings: [{ field: "truth.effect", candidateId: "p-1" }] }));
  expect(mocks.productRequest).toHaveBeenCalledWith("/vcr/studies/study-1/model-sources/source-1");
  await userEvent.selectOptions(screen.getByLabelText("已有文献"), "");
  expect(onChange).toHaveBeenLastCalledWith(null);
});
it("adds DOI through existing source intake and uploads into the selected study project", async () => {
  mocks.addSourceLink.mockResolvedValue({ source });
  const file = new File(["paper"], "paper.pdf"); mocks.pickFiles.mockResolvedValue([file]);
  render(<VcrLiteratureSource studyId="study-1" projectId="project-1" onChange={vi.fn()} />);
  await userEvent.type(screen.getByLabelText("文献 DOI 或链接"), "10.1234/example");
  await userEvent.click(screen.getByRole("button", { name: "加入文献" }));
  await waitFor(() => expect(mocks.addSourceLink).toHaveBeenCalledWith("project-1", "https://doi.org/10.1234/example"));
  await userEvent.click(screen.getByRole("button", { name: "上传文献" }));
  await waitFor(() => expect(mocks.uploadFilesToWorkspace).toHaveBeenCalledWith([file], "knowledge-base", "base", "project-1"));
});
it("shows unreadable source failure without claiming an executable model", async () => {
  mocks.productRequest.mockRejectedValue(new Error("unavailable"));
  const onChange = vi.fn();
  render(<VcrLiteratureSource studyId="study-1" projectId="project-1" onChange={onChange} />);
  await screen.findByRole("option", { name: "Outcome trial" });
  await userEvent.selectOptions(screen.getByLabelText("已有文献"), "source-1");
  await userEvent.click(screen.getByRole("button", { name: "读取文献参数" }));
  expect(await screen.findByRole("alert")).toBeInTheDocument();
  expect(onChange).toHaveBeenLastCalledWith(null);
  expect(screen.queryByLabelText("参数化参考场景")).not.toBeInTheDocument();
});
