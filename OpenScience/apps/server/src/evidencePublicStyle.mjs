// The public evidence pages' stylesheet, generated from the design-token package (flywheel F08, 2026-10-06).
//
// The pages are server-rendered without the React bundle, so they cannot read `index.css`; and a hand-written copy of the product's
// colours would drift from it the first time a token moved. This module reads the same table the web app's generated CSS reads
// (`COLOR_ROLES`, `TYPE_SCALE`, `SPACE`, `CONTAINERS`, `RADII`, `BREAKPOINTS`, `FONT_STACKS`) and writes a small sheet: no colour in it
// is written by hand, no web font is requested (the stack names faces the reader's system already has), no image is needed, and the
// dark scheme follows the reader's system setting. Under 640px (`BREAKPOINTS.sm`) the layout is one column.
//
// The sheet is served at `<base>/assets/site.css` (`/evidence/assets/site.css` unless the deployment serves the pages elsewhere), so the
// pages' Content-Security-Policy admits it by path (`style-src 'self'`) and no page carries an inline style.

import { createHash } from "node:crypto";
import { BREAKPOINTS, CONTAINERS, FONT_STACKS_EN, FONT_STACKS, RADII, SPACE, TYPE_SCALE, colorRole, rem, remLineHeight } from "@evimed/design-tokens";
import { evidencePublicPath } from "./evidencePublicPaths.mjs";

/** The roles the pages use, each a CSS variable of the same name. */
const ROLES = [
  "bg", "surface", "surface-1", "surface-2", "border-hairline", "border-light", "text", "text-2", "text-3", "accent", "accent-fg", "accent-soft", "accent-strong",
  "ok", "ok-soft", "info", "info-soft", "warn", "warn-soft", "warn-strong", "danger", "danger-soft", "danger-strong", "link", "verify-ok", "verify-pending", "highlight",
];

/** @param {"light" | "dark"} scheme */
const variables = (scheme) => ROLES.map((role) => `  --${role}: ${colorRole(role, scheme)};`).join("\n");

/** One rung of the type scale as a font declaration. @param {keyof typeof TYPE_SCALE} name */
const rung = (name) => `font-size: ${rem(TYPE_SCALE[name].size)}; line-height: ${remLineHeight(TYPE_SCALE[name].lineHeight)};`;

const gap = (/** @type {number} */ step) => rem(SPACE.scale[step]);

