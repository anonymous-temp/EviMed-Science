let cached = /** @type {{ css: string, etag: string } | null} */ (null);

/** The stylesheet and its entity tag (the same bytes always give the same tag, so a release that changes a token changes the tag). */
export function evidencePublicStylesheet() {
  if (!cached) {
    const css = build();
    cached = { css, etag: `"${createHash("sha256").update(css).digest("hex").slice(0, 32)}"` };
  }
  return cached;
}

/** Where the sheet is served: the pages' stylesheet link and the router's own path. */
export const evidencePublicStylesheetPath = () => evidencePublicPath("/assets/site.css");
