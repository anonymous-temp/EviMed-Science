import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { after, before, test } from "node:test";
import { ControlPlaneDatabase } from "../src/controlPlaneDatabase.mjs";
import { ProductDocuments } from "../src/productStore.mjs";
import { ProductJobs } from "../src/productJobs.mjs";
import { SourceService } from "../src/sourceService.mjs";
import { VcrStore } from "../src/vcrStore.mjs";
import { VcrService } from "../src/vcrService.mjs";
import { VcrJobs } from "../src/vcrJobs.mjs";
import { createVcrModelSources } from "../src/vcrModelSources.mjs";
import { createGeoTestDatabase } from "./helpers/geoTestDatabase.mjs";
const databaseUrl = process.env.OPEN_SCIENCE_TEST_POSTGRES_URL ?? "";
const options = { skip: !databaseUrl && "OPEN_SCIENCE_TEST_POSTGRES_URL is not configured" };
let isolated, database;
before(async () => { if (!databaseUrl) return; isolated = await createGeoTestDatabase(databaseUrl, "vcrpapers"); database = new ControlPlaneDatabase({ databaseUrl: isolated.url, databasePoolMax: 5, databaseConnectionTimeoutMs: 3000 }); await database.migrate(); });
after(async () => { await database?.close(); if (isolated) await isolated.drop(); });
test("a preserved paper becomes a source-bound reference configuration and real queued job without certifying a fitted model", options, async () => {
  const user = { id: "vcr-paper-owner" };
  await database.query("INSERT INTO evimed_control.users (id,name,auth_type) VALUES ($1,'Paper owner','development')", [user.id]);
  await database.query("INSERT INTO evimed_control.projects (user_id,id,name,quota_bytes) VALUES ($1,'paper-project','Paper project',1048576)", [user.id]);
  const productJobs = new ProductJobs(database);
  const sources = new SourceService(new ProductDocuments(database), productJobs);
  const text = "Control response was 40%; intervention response was 60%.";
  const { source } = await sources.register(user.id, { projectId: "paper-project", connector: { type: "upload", id: "library" }, path: "knowledge-base/trial.txt", sha256: createHash("sha256").update(text).digest("hex"), size: text.length, mimeType: "text/plain", mtime: "2026-10-19T00:00:00Z" });
  const ingest = await productJobs.claim(["ingest"], "vcr-source-fixture", { leaseMs: 3000 });
  await sources.beginIngestion(user.id, source.id, { generation: source.payload.generation, job: ingest });
  await sources.freezeCapture(ingest, { text, summary: "Trial source", extractor: { name: "fixture", version: "1", parser: "fallback" }, units: [{ id: "page1", unitType: "page", status: "extracted", itemIds: [] }] });
  const store = new VcrStore({ database });
  const study = await store.createStudy({ userId: user.id, projectId: "paper-project", name: "Paper study", dataTier: "T0" });
  const service = new VcrService({ store, config: { vcrEnabled: true, vcrAudience: "all" } });
  service.attach({ modelSources: createVcrModelSources({ sources }) });
  const preview = await service.modelSourcePreview(user, study.id, source.id);
  assert.equal(preview.parameters.length, 2);
  await assert.rejects(service.modelSourcePreview({ id: "other-user" }, study.id, source.id), { code: "vcr_study_not_found" });
  const foreignProjectStudy = await store.createStudy({ userId: user.id, projectId: "other-project", name: "Other project", dataTier: "T0" });
  await assert.rejects(service.modelSourcePreview(user, foreignProjectStudy.id, source.id), { code: "source_not_found" });
  const model = await service.adoptModel(user, { studyId: study.id, name: "Trial reference", version: "1", card: { literatureSource: preview, executionProfile: "patients.binary", executionSpec: { invented: true }, parameterBindings: [
    { field: "truth.controlRate", candidateId: preview.parameters[0].id, value: 0.99 }, { field: "truth.treatmentRate", candidateId: preview.parameters[1].id },
  ] } });
  const stored = (await store.models(user.id)).find(row => row.id === model.id);
  assert.equal(stored.card.registrationState, "parameterized_reference");
  assert.deepEqual(stored.evidence, [], "parameterization is not measured validation");
  const scenario = { ...stored.card.executionSpec.scenario, design: { nTreat: 10, nControl: 10 } };
  const sourceModel = await service.modelExecution(user, study, model.id, "generate_patients_binary", scenario);
  await assert.rejects(service.modelExecution(user, study, model.id, "generate_patients_binary", { ...scenario, truth: { ...scenario.truth, controlRate: 0.99 } }), { code: "vcr_model_invalid" });
  const jobs = new VcrJobs({ store, config: {}, engine: null });
  const result = await jobs.enqueue({ studyId: study.id, userId: user.id, kind: "generate_patients_binary", scenario, seed: 42, inputs: [], detail: { sourceModel } });
  assert.equal(result.job.state, "queued", "a real job exists; no successful execution is fabricated");
  assert.equal((await jobs.configuration(study.id, result.job.id)).sourceModel.id, model.id);
  assert.equal((await store.models(user.id)).find(row => row.id === model.id).version, "1");
});
