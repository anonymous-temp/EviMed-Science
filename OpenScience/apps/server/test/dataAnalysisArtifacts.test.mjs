test('Unicode input names respect filesystem byte limits rather than failing during the write', () => {
  assert.equal(analysisFilename('患者数据.csv'), '患者数据.csv');
  assert.throws(() => analysisFilename('患'.repeat(90) + '.csv'), error => error.code === 'analysis_filename_invalid' && error.status === 400);
});

test('specialist snapshots include nested generated figures and tables omitted by the fixed contract', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'analysis-output-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const workspace = path.join(root, 'workspace');
  const destination = path.join(root, 'snapshots');
  for (const directory of ['deliverables/study/figures', 'deliverables/study/tables', 'analysis-inputs/in-1', '.private']) await fs.mkdir(path.join(workspace, directory), { recursive: true });
  await fs.mkdir(destination);
  await fs.writeFile(path.join(workspace, 'deliverables/study/statistical-report.md'), '# Findings');
  await fs.writeFile(path.join(workspace, 'deliverables/study/figures/roc.png'), Buffer.from('actual generated bytes'));
  await fs.writeFile(path.join(workspace, 'deliverables/study/tables/roc.csv'), 'fpr,tpr\n0,0\n1,1\n');
  await fs.writeFile(path.join(workspace, 'analysis-inputs/in-1/cohort.csv'), 'private source');
  await fs.writeFile(path.join(workspace, '.private/token'), 'not an output');
  await fs.symlink(path.join(root, 'snapshots'), path.join(workspace, 'deliverables/study/escape'));
  const result = await snapshotAnalysisRun({ workspaceDir: workspace }, { id: 'run-a', startedAt: new Date(Date.now()-10_000).toISOString(), finishedAt: new Date(Date.now()+1000).toISOString(),
    artifacts: ['deliverables/study/statistical-report.md'] }, destination, { dataAnalysisMaxArtifactBytes: 1024, dataAnalysisMaxSnapshotBytes: 8192 });
  assert.deepEqual(result.artifacts.map(item => item.filename).sort(), ['roc.csv', 'roc.png', 'statistical-report.md']);
  assert.equal(result.artifacts.find(item => item.filename === 'roc.png').role, 'figure');
});

async function snapshotBundles(t, directories, presentedFiles = [], outputFiles = []) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'analysis-bundles-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const workspace = path.join(root, 'workspace'), destination = path.join(root, 'snapshots');
  await fs.mkdir(destination);
  for (const [directory, version] of Object.entries(directories)) {
    await fs.mkdir(path.join(workspace, directory), { recursive: true });
    if(version!==null){
      await fs.writeFile(path.join(workspace, directory, 'analysis-output.json'), JSON.stringify({schemaVersion: 1, summary: `Revision ${version}`, figures: ['figure.svg']}));
      await fs.writeFile(path.join(workspace, directory, 'analysis-results.json'), JSON.stringify({schemaVersion: 1, analyses: [{version}]}));
    }
    await fs.writeFile(path.join(workspace, directory, 'statistical-report.md'), `# Revision ${version}`);
    await fs.writeFile(path.join(workspace, directory, 'figure.svg'), '<svg/>');
  }
  return snapshotAnalysisRun({workspaceDir: workspace}, {id: 'run-bundles', startedAt: new Date(Date.now()-10000).toISOString(), finishedAt: new Date(Date.now()+1000).toISOString(), presentedFiles,outputFiles}, destination,
    {dataAnalysisMaxArtifactBytes: 1024, dataAnalysisMaxSnapshotBytes: 20000});
}

test('nested previous result bundles cannot replace current summary or structured results', async t => {
  const result = await snapshotBundles(t, {'deliverables/revision': 3, 'deliverables/revision/base-v2': 2});
  assert.equal(result.summary, 'Revision 3');
  assert.deepEqual(result.structuredResults, {schemaVersion: 1, analyses: [{version: 3}]});
  assert.equal(result.primaryOutput.resultsPath, 'deliverables/revision/analysis-results.json');
  assert.equal(result.primaryOutput.reportPath, 'deliverables/revision/statistical-report.md');
  assert.equal(result.artifacts.length, 8, 'Previous bytes remain available by their full path and immutable ID.');
  assert.ok(result.notices.some(item => item.code === 'nested_output_bundles'));
});

test('multiple sibling bundles remain explicit alternatives instead of choosing by discovery order', async t => {
  const result = await snapshotBundles(t, {'deliverables/a': 1, 'deliverables/b': 2});
  assert.equal(result.primaryOutput, null);
  assert.equal(result.structuredResults, null);
  assert.equal(result.summary, '');
  assert.equal(result.artifacts.length, 8);
  assert.ok(result.notices.some(item => item.code === 'primary_output_ambiguous'));
});

test('one explicitly presented bundle resolves sibling alternatives without mixing their contents', async t => {
  const result = await snapshotBundles(t, {'deliverables/a': 1, 'deliverables/b': 2}, ['deliverables/b/statistical-report.md']);
  assert.equal(result.primaryOutput.directory, 'deliverables/b');
  assert.equal(result.summary, 'Revision 2');
  assert.deepEqual(result.structuredResults.analyses, [{version: 2}]);
});

test('an explicitly presented nested revision takes precedence over its preserved parent', async t => {
  const result = await snapshotBundles(t, {'deliverables/study': 1, 'deliverables/study/revision': 2}, ['deliverables/study/revision/statistical-report.md']);
  assert.equal(result.primaryOutput.directory, 'deliverables/study/revision');
  assert.equal(result.summary, 'Revision 2');
  assert.deepEqual(result.structuredResults.analyses, [{version: 2}]);
});

test('unavailable selected result markers cannot promote a nested historical bundle', async t => {
  const result = await snapshotBundles(t, {'deliverables/current': null, 'deliverables/current/base-v2': 2}, [],
    ['deliverables/current/analysis-output.json', 'deliverables/current/analysis-results.json', 'deliverables/current/statistical-report.md']);
  assert.equal(result.primaryOutput.directory, 'deliverables/current');
  assert.equal(result.primaryOutput.resultsPath, null);
  assert.equal(result.structuredResults, null);
  assert.equal(result.summary, '# Revision null');
  assert.ok(result.notices.some(item => item.code === 'artifact_unavailable'));
  assert.equal(result.artifacts.length, 6);
});

test('presenting both nested and parent bundles preserves ambiguity', async t => {
  const result = await snapshotBundles(t, {'deliverables/study': 1, 'deliverables/study/revision': 2}, ['deliverables/study/statistical-report.md', 'deliverables/study/revision/statistical-report.md']);
  assert.equal(result.primaryOutput, null);
  assert.equal(result.structuredResults, null);
  assert.ok(result.notices.some(item => item.code === 'primary_output_ambiguous'));
});

async function snapshotOf(t, files, run = {}, limits = {}) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'analysis-capture-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const workspace = path.join(root, 'workspace'), destination = path.join(root, 'snapshots');
  await fs.mkdir(destination); await fs.mkdir(workspace);
  for (const [name, bytes] of Object.entries(files)) await fs.writeFile(path.join(workspace, name), bytes);
  return { workspace, result: () => snapshotAnalysisRun({ workspaceDir: workspace }, { id: 'run-capture', startedAt: new Date(Date.now() - 10000).toISOString(), finishedAt: new Date(Date.now() + 1000).toISOString(), ...run }, destination,
    { dataAnalysisMaxArtifactBytes: 1024, dataAnalysisMaxSnapshotBytes: 8192, ...limits }) };
}

test('a file the service may not read, one over the byte limit and one over the preserved-bytes limit are listed with their reasons and the rest is returned', { skip: process.getuid?.() === 0 }, async t => {
  const fixture = await snapshotOf(t, { 'report.md': '# Findings', 'locked.csv': 'a,b\n1,2', 'model.bin': Buffer.alloc(2000, 1), 'fits.csv': 'x\n1' },
    { artifacts: ['report.md', 'locked.csv', 'model.bin', 'fits.csv', 'absent.png'] }, {});
  await fs.chmod(path.join(fixture.workspace, 'locked.csv'), 0o000);
  const result = await fixture.result();
  assert.deepEqual(result.artifacts.map(item => item.filename).sort(), ['fits.csv', 'report.md']);
  const unavailable = Object.fromEntries(result.notices.filter(item => item.code === 'artifact_unavailable').map(item => [item.path, item.reason]));
  assert.deepEqual(unavailable, { 'locked.csv': 'unreadable', 'model.bin': 'too_large', 'absent.png': 'missing' });
  const small = await snapshotOf(t, { 'a.csv': 'x'.repeat(100), 'b.csv': 'y'.repeat(100) }, { artifacts: ['a.csv', 'b.csv'] }, { dataAnalysisMaxSnapshotBytes: 150 });
  const limited = await small.result();
  assert.deepEqual(limited.artifacts.map(item => item.filename), ['a.csv']);
  assert.deepEqual(limited.notices.find(item => item.code === 'artifact_unavailable'), { code: 'artifact_unavailable', path: 'b.csv', reason: 'snapshot_limit' });
});

test('only files the run declared inherit its verification; scratch files found by change detection do not', async t => {
  const fixture = await snapshotOf(t, { 'report.md': '# Findings', 'figure.png': 'png', 'scratch.csv': 'tmp', 'partial.csv': 'p' },
    { verification: 'verified', artifacts: ['report.md'], presentedFiles: ['figure.png'], unverifiedArtifacts: ['partial.csv'] });
  const marks = Object.fromEntries((await fixture.result()).artifacts.map(item => [item.filename, item.verification]));
  assert.deepEqual(marks, { 'report.md': 'verified', 'figure.png': 'verified', 'scratch.csv': 'unverified', 'partial.csv': 'unverified' });
  const unchecked = await snapshotOf(t, { 'report.md': '# Findings' }, { verification: 'unverified', artifacts: ['report.md'] });
  assert.equal((await unchecked.result()).artifacts[0].verification, 'unverified', 'a run that was not verified verifies nothing');
});
