#!/usr/bin/env node
/**
 * Writes axe-core's browser build into scripts/ops/ui-walk.mjs (R13, V-6).
 *
 * The release switch runs the walk in a throwaway container of the runtime image with one file mounted: ui-walk.mjs. A dependency the walk
 * is to use there has to be in that file, and axe-core (which the walk scans every page with) is in neither the runtime image nor the web
 * image. So the walk carries a copy: the build compressed with brotli, as text between two marker lines, under axe-core's own notice, which
 * its licence (MPL-2.0) requires in any file that holds a substantial part of the source. The walk checks the copy against the checksum
 * written beside it before it uses it, and a test holds it equal to the package where the package is installed.
 *
 *   node scripts/ops/embed-axe-core.mjs [path/to/axe.min.js]        # default: the axe-core of the pnpm store
 *   node scripts/ops/embed-axe-core.mjs --check [path/to/axe.min.js] # exit 1 when the copy in the walk is not that build
 *
 * Build to delete: when the runtime image ships axe-core (or the release switch mounts it), the markers and this script go and the walk
 * reads the file it is given (`OPEN_SCIENCE_WALK_AXE`).
 */
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { brotliCompressSync, constants } from "node:zlib";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const walk = path.join(root, "scripts/ops/ui-walk.mjs");
export const BEGIN = "// BEGIN EMBEDDED AXE-CORE (generated by scripts/ops/embed-axe-core.mjs; do not edit by hand)";
export const END = "// END EMBEDDED AXE-CORE";

/** The axe-core build of the pnpm store (the one eslint-plugin-jsx-a11y brings), or null. */
async function installed() {
  const store = path.join(root, "node_modules/.pnpm");
  const found = (await readdir(store).catch(() => [])).filter((name) => /^axe-core@\d/.test(name)).sort();
  return found.length ? path.join(store, found[found.length - 1], "node_modules/axe-core/axe.min.js") : null;
}

/**
 * The text that goes between the markers for a build of axe-core.
 * @param {string} source axe.min.js @returns {string}
 */
export function embeddedBlock(source) {
  const banner = /^\s*(\/\*![\s\S]*?\*\/)/.exec(source)?.[1];
  const version = /^\s*\/\*!\s*axe v(\d+\.\d+\.\d+)/.exec(source)?.[1];
  if (!banner || !version || !source.includes("axe.run")) throw new Error("that file is not axe-core's browser build");
  const compressed = brotliCompressSync(Buffer.from(source, "utf8"), { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).toString("base64");
  const lines = compressed.match(/.{1,120}/g) ?? [];
  return [
    BEGIN,
    "// axe-core's notice, as the licence asks it in every file that holds a substantial part of the source:",
    banner,
    "const AXE_EMBEDDED = {",
    `  version: "${version}",`,
    `  sha256: "${createHash("sha256").update(source).digest("hex")}",`,
    "  brotliBase64: `",
    ...lines,
    "`.replace(/\\s+/g, \"\"),",
    "};",
    END,
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const file = args.find((arg) => !arg.startsWith("--")) ?? await installed();
  if (!file) {
    console.error("no axe-core build was named and none is installed; pass the path of axe.min.js");
    process.exit(2);
  }
  const block = embeddedBlock(await readFile(file, "utf8"));
  const text = await readFile(walk, "utf8");
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < start) {
    console.error(`${walk} has no embedded-axe block between its markers`);
    process.exit(2);
  }
  const current = text.slice(start, end + END.length);
  if (check) {
    if (current === block) console.log(`the copy in ui-walk.mjs is ${file}`);
    else console.log(`the copy in ui-walk.mjs is not ${file}`);
    process.exit(current === block ? 0 : 1);
  }
  await writeFile(walk, `${text.slice(0, start)}${block}${text.slice(end + END.length)}`);
  console.log(`wrote axe-core from ${file} into ${path.relative(root, walk)} (${block.length} characters)`);
}
