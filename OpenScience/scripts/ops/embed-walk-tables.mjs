#!/usr/bin/env node
/**
 * Writes the walk's two tables into scripts/ops/ui-walk.mjs (R19, plan §3 S9).
 *
 * `page-templates.json` (the pages the walk visits, their template and budgets) and `ui-walk-baseline.json` (what the walk accepts for
 * now, with an owner and a deadline) are the editable sources. The release switch runs the walk in a throwaway container with one file
 * mounted, ui-walk.mjs, and `rewalk.sh` is given a candidate walk file the same way, so a table the walk reads at run time has to be in
 * that file. This script writes the copy between two marker lines, in the layout `formatTables` gives it (one view or entry per line, so a
 * change to a table is a change of lines and not of one long one), and `--check` says whether the copy is the sources. A test holds the two
 * equal (apps/server/test/uiWalk.test.mjs) and the walk's own unit tests read the sources, so editing only the copy cannot pass.
 *
 *   node scripts/ops/embed-walk-tables.mjs           # write the copy
 *   node scripts/ops/embed-walk-tables.mjs --check   # exit 1 when the copy in the walk is not the sources
 *
 * Build to delete: when the release switch mounts the directory (or both files) and `rewalk.sh` copies them, the markers and this script
 * go and the walk reads the files beside it.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const WALK = path.join(root, "scripts/ops/ui-walk.mjs");
export const PAGE_TEMPLATES = path.join(root, "scripts/ops/page-templates.json");
export const BASELINE = path.join(root, "scripts/ops/ui-walk-baseline.json");
export const BEGIN = "// BEGIN EMBEDDED WALK TABLES (generated by scripts/ops/embed-walk-tables.mjs from page-templates.json and ui-walk-baseline.json; do not edit by hand)";
export const END = "// END EMBEDDED WALK TABLES";

/**
 * A value as source text: an array of objects one element to a line, an object holding objects one key to a line, everything else inline.
 * @param {unknown} value @param {number} depth
 * @returns {string}
 */
export function formatTables(value, depth = 0) {
  const pad = "  ".repeat(depth + 1);
  const close = "  ".repeat(depth);
  if (Array.isArray(value) && value.some((item) => item !== null && typeof item === "object")) {
    return `[\n${value.map((item) => `${pad}${JSON.stringify(item)}`).join(",\n")}\n${close}]`;
  }
  if (value !== null && typeof value === "object" && !Array.isArray(value) && Object.values(value).some((item) => item !== null && typeof item === "object")) {
    return `{\n${Object.entries(value).map(([key, item]) => `${pad}${JSON.stringify(key)}: ${formatTables(item, depth + 1)}`).join(",\n")}\n${close}}`;
  }
  return JSON.stringify(value);
}

/**
 * The text that goes between the markers.
 * @param {unknown} pageTemplates @param {unknown} baseline
 */
export function embeddedBlock(pageTemplates, baseline) {
  return [BEGIN, `const WALK_TABLES = ${formatTables({ pageTemplates, baseline })};`, END].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes("--check");
  const block = embeddedBlock(JSON.parse(await readFile(PAGE_TEMPLATES, "utf8")), JSON.parse(await readFile(BASELINE, "utf8")));
  const text = await readFile(WALK, "utf8");
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < start) {
    console.error(`${WALK} has no embedded-tables block between its markers`);
    process.exit(2);
  }
  const current = text.slice(start, end + END.length);
  if (check) {
    console.log(current === block ? "the tables in ui-walk.mjs are page-templates.json and ui-walk-baseline.json" : "the tables in ui-walk.mjs are not page-templates.json and ui-walk-baseline.json: run node scripts/ops/embed-walk-tables.mjs");
    process.exit(current === block ? 0 : 1);
  }
  await writeFile(WALK, `${text.slice(0, start)}${block}${text.slice(end + END.length)}`);
  console.log(`wrote the walk's tables into ${path.relative(root, WALK)} (${block.length} characters)`);
}
